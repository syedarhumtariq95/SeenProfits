/// Enum representing the different platforms the application can run on.
///
/// This enum is used to identify the operating system or environment
/// where the application is currently running.
enum ApplicationPlatforms {
  /// Indicates that the application is running on iOS.
  IOS,

  /// Indicates that the application is running on Android.
  ANDROID,

  /// Indicates that the application is running on an unsupported or unknown platform.
  OTHER,
}
